export async function generateMetadata({ params }: PageProps<'/[slug]'>): Promise<Metadata> {
  const { slug } = await params;
  const page = legalPages.find((p) => p.href === `/${slug}`);
  return page ? { title: page.title, alternates: { canonical: page.href } } : {};
}

export default async function LegalPage({ params }: PageProps<'/[slug]'>) {
  const { slug } = await params;
  const page = legalPages.find((p) => p.href === `/${slug}`);
  if (!page) notFound();
  return (
    <article className="mx-auto max-w-2xl py-12">
      <h1 className="font-display text-4xl">{page.title}</h1>
      <div className="prose-mr mt-6">{content[slug]}</div>
    </article>
  );
}
